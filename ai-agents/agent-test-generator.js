const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const TESTS_DIR = path.join(ROOT, 'tests');
const CONFIG_DIR = path.join(TESTS_DIR, 'config');
const SAMPLE_TICKET_FILE = path.join(__dirname, 'jira-tickets-sample.json');
const DEFAULT_OUTPUT = path.resolve(ROOT, 'agent-test-generator-output.json');

// ── Helpers ────────────────────────────────────────────────────────────────

function log(msg) {
  console.log(`[agent-test-generator] ${msg}`);
}

function error(msg) {
  console.error(`[agent-test-generator] ERROR: ${msg}`);
}

function loadEnvConfig() {
  const env = process.env.ENV || 'dev';
  const configPath = path.join(CONFIG_DIR, 'test-data', `${env}.json`);
  return JSON.parse(fs.readFileSync(configPath, 'utf-8'));
}

function loadTicket(filePath) {
  const raw = fs.readFileSync(filePath, 'utf-8');
  const parsed = JSON.parse(raw);
  const tickets = Array.isArray(parsed) ? parsed : [parsed];
  return tickets;
}

function toPascalCase(str) {
  return str
    .replace(/[^a-zA-Z0-9 ]/g, ' ')
    .split(/\s+/)
    .map(w => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
    .join('');
}

function camelToTitle(str) {
  return str
    .replace(/([A-Z])/g, ' $1')
    .replace(/^./, s => s.toUpperCase())
    .trim();
}

const COMPONENT_MODULE_MAP = {
  login: 'spec-login',
  dashboard: 'spec-dashboard',
  cart: 'spec-cart',
  orders: 'spec-orders',
  checkout: 'spec-checkout',
  register: 'spec-login',
  password: 'spec-login',
};

function stripSpecPrefix(dir) {
  return dir.replace(/^spec-/, '');
}

function resolveModule(component) {
  return COMPONENT_MODULE_MAP[component.toLowerCase()] || component.toLowerCase();
}

function inferTestType(ticket) {
  const desc = (ticket.description || '').toLowerCase();
  const labels = (ticket.labels || []).map(l => l.toLowerCase());
  if (labels.includes('api') || desc.includes('endpoint') || desc.includes('api')) return 'api';
  return 'ui';
}

function findConfigUrl(config, module) {
  const urls = config.urls || {};
  const key = stripSpecPrefix(module);
  if (urls[module]) return urls[module];
  if (urls[key]) return urls[key];
  if (urls.login) return urls.login;
  return urls.client || urls.base || '';
}

function generateApiSpecContent(ticket, config, analysis) {
  const pascalModule = toPascalCase(ticket.component);
  const featureTitle = ticket.summary;
  const ticketTag = `@jira-${ticket.id}`;
  const moduleDir = resolveModule(ticket.component);

  const hasAuth = (ticket.labels || []).includes('auth') || ticket.description.toLowerCase().includes('auth');
  const fixtureArgs = hasAuth ? '({ request, authToken })' : '({ request })';
  const headers = hasAuth ? '\n      headers: { authorization: authToken }' : '';

  let analysisHints = '';
  if (analysis) {
    if (analysis.endpoints && analysis.endpoints.length > 0) {
      analysisHints = `\n// API endpoints discovered:\n// ${analysis.endpoints.join('\n// ')}\n`;
    }
  }

  const endpointKey = stripSpecPrefix(moduleDir);
  return `// ${ticket.id}: ${ticket.summary}
// Description: ${ticket.description}
// Priority: ${ticket.priority}
// Labels: ${(ticket.labels || []).join(', ')}
// Generated by agent-test-generator on ${new Date().toISOString().split('T')[0]}
${analysisHints}
const { test, expect } = require('../../fixtures');
const { urls } = require('../../config');

test.describe('${pascalModule} API - ${featureTitle}', () => {

  test('${ticket.id}: ${ticket.summary} ${ticketTag} @api', async ${fixtureArgs} => {
    // TODO: Implement test based on ticket description
    // ${ticket.description}
    const endpoint = urls.${endpointKey} || '/api/endpoint';
    const response = await request.post(endpoint, {${headers}
      data: { /* TODO: add request body */ }
    });
    expect(response.status()).toBe(200);
    const body = await response.json();
    expect(body).toBeTruthy();
  });

});
`;
}

function generateUiSpecContent(ticket, config, analysis) {
  const featureTitle = ticket.summary;
  const ticketTag = `@jira-${ticket.id}`;
  const moduleDir = resolveModule(ticket.component);
  const needsAuth = !['login', 'register', 'password'].includes(ticket.component.toLowerCase());

  let analysisHints = '';
  if (analysis) {
    if (analysis.elements && analysis.elements.length > 0) {
      analysisHints = `\n// Page elements discovered via playwright-cli:\n// ${analysis.elements.join('\n// ')}`;
    }
  }

  const pageUrl = findConfigUrl(config, moduleDir);

  const testCases = [];
  testCases.push(`  test('${ticket.id}_positive: Verify ${featureTitle} loads and works correctly ${ticketTag} @ui', async ({ ${needsAuth ? 'loggedInPage, poManager' : 'page, poManager'} }) => {
    // TODO: Implement based on ticket description
    // ${ticket.description}
    ${needsAuth
      ? "    const dashboardPage = poManager.getDashboardPage();\n    await dashboardPage.waitForDashboardReady();"
      : "    await poManager.getLoginPage().goto();"}
    // Add assertions here
    await expect(true).toBeTruthy();
  });`);

  return `// ${ticket.id}: ${ticket.summary}
// Description: ${ticket.description}
// Priority: ${ticket.priority}
// Labels: ${(ticket.labels || []).join(', ')}
// Generated by agent-test-generator on ${new Date().toISOString().split('T')[0]}
// Analyzed URL: ${pageUrl}
${analysisHints}
const { test, expect } = require('../fixtures');
const { credentials, urls } = require('../config');

test.describe('${camelToTitle(moduleDir)} - ${featureTitle}', () => {

${testCases.join('\n\n')}

});
`;
}

function analyzePageWithPlaywrightCli(url) {
  try {
    log(`Analyzing page: ${url}`);
    const snapshot = execSync(`npx playwright-cli --raw snapshot --boxes`, {
      timeout: 30000,
      encoding: 'utf-8',
      stdio: ['pipe', 'pipe', 'pipe'],
    });

    const elements = (snapshot || '')
      .split('\n')
      .filter(l => l.includes('e') && (l.includes('button') || l.includes('input') || l.includes('a[')))
      .map(l => l.trim())
      .slice(0, 20);

    let endpoints = [];
    try {
      const requests = execSync(`npx playwright-cli --raw requests`, {
        timeout: 15000,
        encoding: 'utf-8',
        stdio: ['pipe', 'pipe', 'pipe'],
      });
      endpoints = (requests || '')
        .split('\n')
        .filter(l => l.includes('/api/'))
        .map(l => l.trim())
        .slice(0, 10);
    } catch (_) {}

    log(`Found ${elements.length} elements and ${endpoints.length} API endpoints`);
    return { elements, endpoints };
  } catch (e) {
    log(`Page analysis skipped: ${e.message}`);
    return null;
  }
}

function writeSpecFile(ticket, content) {
  const moduleDir = resolveModule(ticket.component);
  const testType = inferTestType(ticket);
  const specName = toPascalCase(ticket.summary.replace(/[^a-zA-Z0-9 ]/g, ' '));

  let specDir;
  let fileName;
  if (testType === 'api') {
    specDir = path.join(TESTS_DIR, moduleDir, 'api');
    fileName = `${specName}.api.spec.js`;
  } else {
    specDir = path.join(TESTS_DIR, moduleDir);
    fileName = `${specName}test.spec.js`;
  }

  if (!fs.existsSync(specDir)) {
    fs.mkdirSync(specDir, { recursive: true });
    log(`Created directory: ${specDir}`);
  }

  const filePath = path.join(specDir, fileName);
  if (fs.existsSync(filePath)) {
    const existing = fs.readFileSync(filePath, 'utf-8');
    if (existing.includes(`@jira-${ticket.id}`)) {
      log(`Test for ${ticket.id} already exists in ${filePath} — skipping`);
      return { filePath, status: 'skipped', reason: 'already exists' };
    }
    // Append if file exists but no matching ticket tag
    fs.writeFileSync(filePath, existing + '\n' + content);
    log(`Appended to existing file: ${filePath}`);
  } else {
    fs.writeFileSync(filePath, content);
    log(`Created: ${filePath}`);
  }

  return { filePath, status: 'created' };
}

async function runTests(filePaths) {
  const results = [];
  for (const { filePath, status } of filePaths) {
    if (status === 'skipped') {
      results.push({ file: filePath, status: 'skipped' });
      continue;
    }
    const relativePath = path.relative(TESTS_DIR, filePath);
    try {
      log(`Running: ${relativePath}`);
      const output = execSync(`npx playwright test "${relativePath}" --reporter=line`, {
        cwd: ROOT,
        timeout: 120000,
        encoding: 'utf-8',
        stdio: ['pipe', 'pipe', 'pipe'],
      });
      log(`PASS: ${relativePath}`);
      results.push({ file: relativePath, status: 'passed', output: output.trim() });
    } catch (e) {
      error(`FAIL: ${relativePath}`);
      results.push({ file: relativePath, status: 'failed', output: (e.stdout || '') + (e.stderr || '') });
    }
  }
  return results;
}

// ── Main ───────────────────────────────────────────────────────────────────

async function main() {
  const args = process.argv.slice(2);
  const ticketFile = args.find(a => !a.startsWith('--'));
  const shouldRun = args.includes('--run');
  const skipAnalysis = args.includes('--no-analyze');

  if (!ticketFile) {
    error('No ticket file provided');
    console.log('\nUsage: node ai-agents/agent-test-generator.js <ticket.json> [--run] [--no-analyze]');
    console.log(`Example: node ai-agents/agent-test-generator.js ${SAMPLE_TICKET_FILE} --run`);
    console.log('\nTicket JSON format: see ai-agents/jira-tickets-sample.json');
    process.exit(1);
  }

  if (!fs.existsSync(ticketFile)) {
    error(`Ticket file not found: ${ticketFile}`);
    process.exit(1);
  }

  const config = loadEnvConfig();
  const tickets = loadTicket(ticketFile);
  log(`Loaded ${tickets.length} ticket(s) from ${ticketFile}`);

  const results = [];

  for (const ticket of tickets) {
    log(`Processing ${ticket.id}: ${ticket.summary}`);

    const testType = inferTestType(ticket);
    const baseUrl = findConfigUrl(config, resolveModule(ticket.component));

    // Analyze page if not skipped
    let analysis = null;
    if (!skipAnalysis && baseUrl) {
      analysis = analyzePageWithPlaywrightCli(baseUrl);
    }

    let content;
    if (testType === 'api') {
      content = generateApiSpecContent(ticket, config, analysis);
    } else {
      content = generateUiSpecContent(ticket, config, analysis);
    }

    const result = writeSpecFile(ticket, content);
    results.push({ ticket: ticket.id, summary: ticket.summary, ...result });
  }

  // Run tests if requested
  let testResults = [];
  let allPassed = true;
  if (shouldRun) {
    log('Running generated tests...');
    testResults = await runTests(results.filter(r => r.status === 'created').map(r => ({ filePath: r.filePath, status: r.status })));
    allPassed = testResults.every(r => r.status === 'passed' || r.status === 'skipped');
  }

  // Summary
  console.log('\n' + '='.repeat(60));
  console.log('AGENT TEST GENERATOR — SUMMARY');
  console.log('='.repeat(60));
  results.forEach(r => {
    console.log(`  ${r.ticket}: ${r.status === 'created' ? '✓ Created' : r.status === 'skipped' ? '− Skipped' : '✗ Failed'} — ${r.summary}`);
    if (r.filePath) console.log(`       ${r.filePath}`);
  });

  if (shouldRun) {
    console.log('\n--- Test Results ---');
    testResults.forEach(r => {
      console.log(`  ${r.status === 'passed' ? '✓' : r.status === 'skipped' ? '−' : '✗'} ${r.file}`);
    });
  }

  const output = {
    timestamp: new Date().toISOString(),
    ticketFile,
    env: process.env.ENV || 'dev',
    generated: results,
    testResults: shouldRun ? testResults : undefined,
    allPassed: shouldRun ? allPassed : undefined,
  };
  fs.writeFileSync(DEFAULT_OUTPUT, JSON.stringify(output, null, 2));
  log(`Full output saved to ${DEFAULT_OUTPUT}`);

  if (!allPassed && shouldRun) process.exit(1);
}

main().catch(err => {
  error(err.message);
  process.exit(1);
});
